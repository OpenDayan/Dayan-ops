import subprocess
import sys
import re


if len(sys.argv) < 2:
    print("Usage: python NPULinker.py [your elf file]")

OUTPUT_FILE_NAME = sys.argv[2] if len(sys.argv) > 2 else 'general_kernel.gen.c'
INPUT_FILE_NAME = str(sys.argv[1])
TEXT_SECTION_NAME = '.text.npu_kernel'

if INPUT_FILE_NAME.endswith('.elf'):
    INPUT_FILE_NAME = INPUT_FILE_NAME[:-4]

# 得到二进制文件的数组变量名
bare_name = '__' + INPUT_FILE_NAME
array_name = re.sub(r'[^a-zA-Z0-9]', '_', bare_name + '.bin')
struct_name = re.sub(r'[^a-zA-Z0-9]', '_', bare_name)

# ---- Step0: objcopy 获取 bin
subprocess.run(['riscv64-unknown-elf-objcopy', '-O', 'binary', INPUT_FILE_NAME + '.elf', INPUT_FILE_NAME + '.bin'], check=True)

# ---- Step1: 获取二进制数组头文件
with open(INPUT_FILE_NAME + '.bin', "rb") as rf:
    first = True
    with open(OUTPUT_FILE_NAME, "w") as wf:
        wf.write("// This file is automatically generated\n#include <stdlib.h>\n#include <stdint.h>\n#include \"NPURuntime.h\"\n")
        wf.write("static uint8_t " + array_name + "[] = {\n")
        while True:
            byte = rf.read(1)
            if not byte:
                break
            if first:
                first = False
            else:
                wf.write(", ")
            # Convert byte to hex and format it
            wf.write("0x{:02x}".format(byte[0]))
        wf.write("\n};\n")

# ---- Step2: 抓取Kernel函数信息 -----------
# objdump -t a.elf
objdump = subprocess.Popen(['riscv64-unknown-elf-objdump', '-t', INPUT_FILE_NAME + '.elf'], stdout=subprocess.PIPE, text=True)
# grep '.npu_kernel'
grep = subprocess.Popen(['grep', '-E', TEXT_SECTION_NAME + '|entry_args|_heap|__perf_counter'], stdin=objdump.stdout, stdout=subprocess.PIPE, text=True)
# awk '{print $6, $1}'
awk_kernel = subprocess.Popen(['awk', "{print $6, $1, $5}"], stdin=grep.stdout, stdout=subprocess.PIPE, text=True)
# 输出
output, _ = awk_kernel.communicate()
print(output)
# ---- Step3: 输出 -------------------------
kernel_count = 0
args_ptr = ''
perf_ptr = ''
heap_addr = ''

out_desc_table = 'static struct NPUKernelDesc kernel_desc_table[] = {\n'
# 获取kernel名称和地址
for kernel in output.split('\n')[:-1]:
    [name, entry, heap_name] = kernel.split(' ')
    entry = entry.lstrip('0') or '0'
    if name == TEXT_SECTION_NAME:
        continue
    elif name == 'entry_args':
        args_ptr = entry
        print(f'entry_args Structure address: 0x{args_ptr}')
    elif name == '__perf_counter':
        perf_ptr = entry
        print(f'perf counter address: 0x{perf_ptr}')
    elif heap_name == '_heap':
        heap_addr = entry
        print(f'heap start address: 0x{heap_addr}')
    else:
        print(f"Kernel Name: {name}, Kernel Entry: 0x{entry}")
        out_desc_table += f'    {{ .entry=0x{entry}, .name="{name}" }},\n'
        kernel_count += 1
out_desc_table += '    { .entry=0x0, .name=NULL }\n};\n'

out_set_desc = 'struct NPUDeviceKernelSetDesc ' + struct_name + ' = {\n' + \
               '    .magic = 0,\n' + \
               '    .flags = 0,\n' + \
               '    .version = 0,\n' + \
               '    .reserve1 = 0,\n' + \
               '    .load_start = 0x80000000,\n' + \
              f'    .load_size = sizeof({array_name}),\n' + \
              f'    .kernel_count = {kernel_count},\n' + \
               '    .general_entry = 0x80000000,\n' + \
              f'    .args_ptr = 0x{args_ptr},\n' + \
              f'    .data = {array_name},\n' + \
               '    .kernels = kernel_desc_table,\n' + \
              f'    .heap = 0x{heap_addr},\n' + \
              f'    .perf = 0x{perf_ptr},\n' + \
               '};\n'


with open(OUTPUT_FILE_NAME, 'a') as f:
    f.write(out_desc_table)
    f.write(out_set_desc)